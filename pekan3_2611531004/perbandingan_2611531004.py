# Buat file dengan nama perbandingan_2611531004.py
# Nama variabel ditambah 4 digit nim terakhir contoh: angka1_1004
# Program ini menggunakan fungsi input()
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# program operator perbandingan dalam Phyton

angka1_1004 = int(input("Input angka-1: "))
angka2_1004 = int(input("Input angka-2: "))

# Lebih besar dari
hasil_1004 = angka1_1004 > angka2_1004
print("\nOperator lebih besar dari")
print("Angka1 > Angka2 =", hasil_1004)

# Lebih kecil dari
hasil_1004 = angka1_1004 < angka2_1004
print("\nOperator lebih kecil dari")
print("Angka1 < Angka2 =", hasil_1004)

# Lebih besar dari atau sama dengan
hasil_1004 = angka1_1004 >= angka2_1004
print("\nOperator lebih besar dari atau sama dengan")
print("Angka1 >= Angka2 =", hasil_1004)

# Lebih kecil dari atau sama dengan
hasil_1004 = angka1_1004 <= angka2_1004
print("\nOperator lebih kecil dari atau sama dengan")
print("Angka1 <= Angka2 =", hasil_1004)

# Sama dengan
hasil_1004 = angka1_1004 == angka2_1004
print("\nOperator sama dengan")
print("Angka1 == Angka2 =", hasil_1004)

# Tidak sama dengan
hasil_1004 = angka1_1004 != angka2_1004
print("\nOperator tidak sama dengan")
print("Angka1 != Angka2 =", hasil_1004)

# Tambahan: perbandingan berantai dalam Phyton
hasil_1004 = 0 < angka1_1004 < 100
print("\nPerbandingan berantai")
print("0 < Angka1 < 100 =", hasil_1004)

hasil_1004 = 0 < angka2_1004 < 100
print("0 < Angka2 < 100 =", hasil_1004)