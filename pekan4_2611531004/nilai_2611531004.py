# Program konversi nilai angka menjadi huruf

nilai_1004 = int(input("Inputkan nilai angka= "))

if nilai_1004 >= 81:
    print("A")
elif nilai_1004 >= 70:
    print("B")
elif nilai_1004 >= 60:
    print("C")
elif nilai_1004 >= 50:
    print("D")
else:
    print("E")