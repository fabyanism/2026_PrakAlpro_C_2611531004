# memasukkan nilai panjang dan lebar persegi panjang.
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
panjang_1004 = int(input('Masukkan nilai panjang: '))
lebar_1004 = int(input('Masukkan nilai lebar: '))
luas_1004 = int(panjang_1004) * int(lebar_1004)
print("Luas =", luas_1004)